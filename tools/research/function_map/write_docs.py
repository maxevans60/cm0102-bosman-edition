"""Writes the function map docs from the placement and one or more naming runs.

Later runs win over earlier ones for the same address (a sweep over one file, a second wave).
Each function also lists the research docs and runtime files that cite its address.

Usage: FUNCMAP_WORK=... write_docs.py <run> [<run> ...]
Writes docs/research/function-map/index.md, names.tsv and one <file>.md per source file.
"""
import collections
import glob
import json
import os
import re
import sys

from common import MAP_DIR, REPO, load, work_dir

HEADER = """# {title}

Function map of the original, 3.9.68. Generated by `tools/research/function_map/write_docs.py`. Do not edit by hand: run a sweep and generate again.

Names are first-pass names from the model shown in each row. Treat a low or medium name as a hint and read the code before you rely on it. "Cited in" lists research docs and runtime files that name the address; they win over the first-pass name.

"""


def cell(s):
    return " ".join(str(s or "").replace("|", "/").split())


def citations(addresses):
    cited = collections.defaultdict(set)
    files = glob.glob(f"{REPO}/docs/**/*.md", recursive=True) + glob.glob(f"{REPO}/src/**/*.[ch]", recursive=True)
    for p in files:
        rel = os.path.relpath(p, REPO)
        if rel.startswith("docs/research/function-map") or os.path.basename(rel).startswith("2026-10-16-function-map-"):
            continue
        for m in re.finditer(r"(?:0x|FUN_|f_|RT_REPLACE\(|RT_WRAP\()0*([0-9a-fA-F]{6})\b", open(p, errors="ignore").read()):
            a = int(m.group(1), 16)
            if a in addresses:
                cited[a].add(os.path.basename(rel))
    return cited


def main(runs):
    P = load("placement.pkl")
    db, cat, fo, gaps, owner = P["db"], P["cat"], P["file_of"], P["gaps"], P["owner"]
    names = {}
    for run in runs:
        for line in open(f"{work_dir()}/runs/{run}/names.jsonl"):
            r = json.loads(line)
            if r.get("name"):
                r.setdefault("model", r.get("tier", ""))
                names[int(r["address"], 16)] = r
    members = sorted(e for e in db if cat[e] in ("game", "lib"))
    cited = citations(set(members))
    funclets = collections.Counter(owner.values())

    def home(e):
        if cat[e] == "lib":
            return "library_without_asserts"
        if e in fo:
            return fo[e]
        pick = names.get(e, {}).get("file", "")
        return pick if pick in gaps[e] else gaps[e][0]

    by_file = collections.defaultdict(list)
    for e in members:
        by_file[home(e)].append(e)
    os.makedirs(MAP_DIR, exist_ok=True)
    for old in glob.glob(f"{MAP_DIR}/*.md"):
        os.remove(old)
    conf = collections.Counter()
    with open(f"{MAP_DIR}/names.tsv", "w") as tsv:
        tsv.write("address\tfile\tname\tconfidence\tmodel\tcited_in\n")
        for f in sorted(by_file, key=str.lower):
            rows = ["| Address | Size | Name | Convention | Purpose | Confidence | Model | Cited in |",
                    "|---|---|---|---|---|---|---|---|"]
            for e in by_file[f]:
                r = names.get(e, {})
                c = r.get("confidence", "none")
                conf[c] += 1
                size = f"{db[e]['n']}" + (f" (+{funclets[e]} unwind)" if funclets[e] else "")
                rows.append(f"| 0x{e:06x} | {size} | `{cell(r.get('name'))}` | {cell(r.get('convention'))} | "
                            f"{cell(r.get('purpose'))} | {c} | {r.get('model', '')} | {cell(', '.join(sorted(cited[e])))} |")
                tsv.write(f"0x{e:06x}\t{f}\t{r.get('name', '')}\t{c}\t{r.get('model', '')}\t{','.join(sorted(cited[e]))}\n")
            title = f"{f}: {len(by_file[f])} functions"
            open(f"{MAP_DIR}/{f}.md", "w").write(HEADER.format(title=title) + "\n".join(rows) + "\n")
    cats = collections.Counter(cat.values())
    index = [HEADER.format(title="Function map index"),
             f"All {len(db)} functions with their category, file and placement method are in `function-files.tsv`. "
             f"All {len(members)} named functions are in `names.tsv`.", "",
             f"- Game functions: {cats['game']}. Library without asserts: {cats['lib']}.",
             f"- Not named, by category: {cats['funclet']} unwind funclets (each belongs to its parent, shown as \"+n unwind\"), "
             f"{cats['ehstub']} exception handler stubs, {cats['crt']} C runtime functions.",
             f"- Confidence: {conf['high']} high, {conf['medium']} medium, {conf['low']} low, {conf['none']} without a name.",
             f"- Runs: {', '.join(runs)}.",
             "- Quality of the Haiku first pass: see \"First pass\" in `../2026-10-16-function-map-estimate.md`.", "", "| File | Functions |", "|---|---|"]
    for f in sorted(by_file, key=str.lower):
        index.append(f"| [{f}]({f}.md) | {len(by_file[f])} |")
    open(f"{MAP_DIR}/index.md", "w").write("\n".join(index) + "\n")
    print(len(by_file), "files", dict(conf))


if __name__ == "__main__":
    main(sys.argv[1:])
