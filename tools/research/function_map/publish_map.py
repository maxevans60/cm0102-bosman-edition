"""Copy the function map and the data map into the public map repo (github.com/maxevans60/cm0102-function-map).

Usage: python3 publish_map.py <path to the cm0102-function-map checkout>

The docs in docs/research/function-map and docs/research/data-map stay the only source. This script
copies them into <repo>/map/ and <repo>/data-map/, swaps the header for one that suits readers outside
this repo, and writes <repo>/map/functions.tsv (every named function with its convention and purpose)
and <repo>/data-map/data.tsv (every global with its type, description, readers and writers) for the search page.
It does not touch README.md, LICENSE or index.html in the map repo. Commit and push there by hand.
"""
import os, re, shutil, sys

SRC = os.path.join(os.path.dirname(__file__), "../../../docs/research/function-map")
DATA_SRC = os.path.join(os.path.dirname(__file__), "../../../docs/research/data-map")
OLD_HEAD = re.compile(
    r"Function map of the original, 3\.9\.68\. Generated by .*?\n\nNames are first-pass names.*?\n", re.S)
NEW_HEAD = (
    "Function map of cm0102.exe 3.9.68. Generated from the Bosman Edition repo. Do not edit by hand: "
    "report a wrong name as an issue.\n\n"
    "AI agents named each function from its code, and a review checked every medium and low name. "
    "Treat a medium or low name as a hint and read the code before you rely on it. "
    "\"Cited in\" lists research docs of the Bosman Edition repo that name the address.\n")

DATA_OLD_HEAD = re.compile(
    r"Data map of the original, 3\.9\.68: (.*?)\. Generated by .*?\n\n(A global is high only when.*?)"
    r"\"Cited in\" lists research docs and runtime files that name the address\.\n", re.S)
DATA_NEW_HEAD = (
    r"Data map of cm0102.exe 3.9.68: \1. Generated from the Bosman Edition repo. Do not edit by hand: "
    r"report a wrong name as an issue." "\n\n" r"\2"
    "\"Cited in\" lists research docs and runtime files of the Bosman Edition repo that name the address." "\n")


def fresh(path):
    if os.path.isdir(path):
        shutil.rmtree(path)
    os.makedirs(path)


def publish_data_map(out):
    dst = os.path.join(out, "data-map")
    fresh(dst)
    rows = []
    for name in sorted(os.listdir(DATA_SRC)):
        p = os.path.join(DATA_SRC, name)
        if name.endswith(".tsv"):
            shutil.copy(p, dst)
            continue
        if not name.endswith(".md"):
            continue
        text = open(p, encoding="utf-8").read()
        text, n = DATA_OLD_HEAD.subn(DATA_NEW_HEAD, text, count=1)
        if not n:
            sys.exit(f"data-map/{name}: header not found")
        text = text.replace("](../function-map/", "](../map/")
        if name == "index.md":
            text = re.sub(r"^- Runs: .*\n", "", text, flags=re.M)
        else:
            for line in text.splitlines():
                if line.startswith("| 0x"):
                    f = [c.strip() for c in line.strip("|").split(" | ")]
                    rows.append([f[0], f[1], name[:-3], f[2], f[3].strip("`"), f[4], f[6], f[7]])
        open(os.path.join(dst, name), "w", encoding="utf-8").write(text)
    access = {}
    for line in open(os.path.join(DATA_SRC, "globals.tsv"), encoding="utf-8").read().splitlines()[1:]:
        g = line.split("\t")
        access[g[0]] = [g[4], g[5]]
    rows = [r + access[r[0]] for r in rows]
    rows.sort(key=lambda r: int(r[0], 16))
    with open(os.path.join(dst, "data.tsv"), "w", encoding="utf-8") as f:
        f.write("address\tsize\tdoc\ttype\tname\tdescription\tconfidence\tmodel\treaders\twriters\n")
        for r in rows:
            f.write("\t".join(c.replace("\t", " ") for c in r) + "\n")
    print(f"copied the data map to {dst}: {len(rows)} globals")


def main(out):
    dst = os.path.join(out, "map")
    fresh(dst)
    rows = []
    for name in sorted(os.listdir(SRC)):
        p = os.path.join(SRC, name)
        if name.endswith(".tsv"):
            shutil.copy(p, dst)
            continue
        if not name.endswith(".md"):
            continue
        text = open(p, encoding="utf-8").read()
        text, n = OLD_HEAD.subn(NEW_HEAD, text, count=1)
        if not n:
            sys.exit(f"{name}: header not found")
        if name == "index.md":
            text = re.sub(r"^- Runs: .*\n", "", text, flags=re.M)
            text = re.sub(r"^- Quality of the Haiku first pass: .*\n", "", text, flags=re.M)
        else:
            for line in text.splitlines():
                if line.startswith("| 0x"):
                    f = [c.strip() for c in line.strip("|").split(" | ")]
                    rows.append([f[0], f[1], name[:-3], f[2].strip("`"), f[3], f[4], f[5], f[6]])
        open(os.path.join(dst, name), "w", encoding="utf-8").write(text)
    rows.sort(key=lambda r: int(r[0], 16))
    with open(os.path.join(dst, "functions.tsv"), "w", encoding="utf-8") as f:
        f.write("address\tsize\tdoc\tname\tconvention\tpurpose\tconfidence\tmodel\n")
        for r in rows:
            f.write("\t".join(c.replace("\t", " ") for c in r) + "\n")
    print(f"copied the map to {dst}: {len(rows)} named rows")
    publish_data_map(out)


if __name__ == "__main__":
    main(sys.argv[1])
