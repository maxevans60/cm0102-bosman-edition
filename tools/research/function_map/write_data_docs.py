"""Writes the data map docs from globals.pkl and one or more naming runs of the globals.

Later runs win over earlier ones for the same address. A global that no run names shows as
g_unk_<address>, low, model script. Each row links to the function map pages of its readers and
writers, and lists the research docs and runtime files that cite its address.

Usage: FUNCMAP_WORK=... write_data_docs.py <run> [<run> ...]
Reads $FUNCMAP_WORK/runs-data/<run>/names.jsonl. Writes docs/research/data-map/index.md,
globals.tsv, shared.md and one <owner file>.md per owner file.
"""
import collections
import csv
import glob
import json
import os
import re
import sys

from common import MAP_DIR, REPO, load, work_dir

DATA_DIR = os.path.join(REPO, "docs", "research", "data-map")
MAX_LINKS = 6
# Files that list addresses by the hundred without saying anything about them.
NOT_CITATIONS = ("key_ids_table.c",)

HEADER = """# {title}

Data map of the original, 3.9.68: the globals that game and library functions touch. Generated by `tools/research/function_map/write_data_docs.py`. Do not edit by hand: run a naming wave and generate again.

A global is high only when the evidence quotes a string, an assert, a constant in read-only data, or a high function whose name pins the purpose. Treat a medium or low name as a hint. Fields of an address group are described as `g_<object>+0x<offset> <field>`. Readers and writers link to the function map. "Cited in" lists research docs and runtime files that name the address.

"""


def cell(s):
    return " ".join(str(s or "").replace("|", "/").split())


def citations(addresses):
    cited = collections.defaultdict(set)
    files = glob.glob(f"{REPO}/docs/**/*.md", recursive=True) + glob.glob(f"{REPO}/src/**/*.[ch]", recursive=True)
    for p in files:
        rel = os.path.relpath(p, REPO)
        base = os.path.basename(rel)
        if rel.startswith(("docs/research/function-map", "docs/research/data-map")) or base in NOT_CITATIONS \
                or base.startswith("2026-10-16-function-map-"):
            continue
        for m in re.finditer(r"(?:0x|DAT_)0*([0-9a-fA-F]{6})\b", open(p, errors="ignore").read()):
            a = int(m.group(1), 16)
            if a in addresses:
                cited[a].add(base)
    return cited


def read_runs(runs):
    names = {}
    for run in runs:
        for line in open(f"{work_dir()}/runs-data/{run}/names.jsonl"):
            r = json.loads(line)
            if r.get("name"):
                names[int(r["address"], 16)] = r
    return names


def rows_for(G, names):
    out = {}
    for a, g in G.items():
        r = names.get(a)
        if r:
            out[a] = dict(r)
        else:
            out[a] = dict(name=f"g_unk_{a:06x}", type=g["type"], size=g["size"], description="", evidence="",
                          confidence="low", model="script")
        out[a].setdefault("type", g["type"])
        out[a].setdefault("size", g["size"])
    # A high row cannot rest on a global that is not high: it drops to medium until that global is high.
    by_name = {r["name"]: r for r in out.values()}
    changed = True
    while changed:
        changed = False
        for r in out.values():
            if r["confidence"] != "high":
                continue
            weak = [q for q in re.findall(r"\bg_[a-z0-9_]+", r.get("evidence", ""))
                    if q != r["name"] and q in by_name and by_name[q]["confidence"] != "high"]
            if weak:
                r["confidence"] = "medium"
                r["evidence"] = f"{r['evidence']} (medium until {', '.join(sorted(set(weak)))} is high)"
                changed = True
    return out


def main(runs):
    D = load("globals.pkl")
    G = D["G"]
    fn = {int(r["address"], 16): r for r in csv.DictReader(open(os.path.join(MAP_DIR, "names.tsv")), delimiter="\t")}
    rows = rows_for(G, read_runs(runs))
    cited = citations(set(G))

    def link(e):
        f = fn.get(e, {}).get("file")
        return f"[0x{e:06x}](../function-map/{f}.md)" if f else f"0x{e:06x}"

    def links(es):
        es = sorted(es)
        s = ", ".join(link(e) for e in es[:MAX_LINKS])
        return s + (f" and {len(es) - MAX_LINKS} more" if len(es) > MAX_LINKS else "")

    by_owner = collections.defaultdict(list)
    for a in sorted(G):
        by_owner[G[a]["owner"]].append(a)
    os.makedirs(DATA_DIR, exist_ok=True)
    for old in glob.glob(f"{DATA_DIR}/*.md"):
        os.remove(old)
    conf, model = collections.Counter(), collections.Counter()
    with open(f"{DATA_DIR}/globals.tsv", "w") as tsv:
        tsv.write("address\tsize\ttype\tname\treaders\twriters\tconfidence\tmodel\tcited_in\n")
        for a in sorted(G):
            r, g = rows[a], G[a]
            conf[r["confidence"]] += 1
            model[r["model"]] += 1
            tsv.write(f"0x{a:06x}\t{r['size']}\t{r['type']}\t{r['name']}\t"
                      f"{','.join(f'0x{e:06x}' for e in g['readers'])}\t{','.join(f'0x{e:06x}' for e in g['writers'])}\t"
                      f"{r['confidence']}\t{r['model']}\t{','.join(sorted(cited[a]))}\n")
    for owner, addrs in by_owner.items():
        lines = ["| Address | Size | Type | Name | Description | Evidence | Confidence | Model | Writers | Readers | Cited in |",
                 "|---|---|---|---|---|---|---|---|---|---|---|"]
        for a in addrs:
            r, g = rows[a], G[a]
            lines.append(f"| 0x{a:06x} | {r['size']} | {cell(r['type'])} | `{cell(r['name'])}` | {cell(r.get('description'))} | "
                         f"{cell(r.get('evidence'))} | {r['confidence']} | {r['model']} | {links(g['writers'])} | "
                         f"{links(g['readers'])} | {cell(', '.join(sorted(cited[a])))} |")
        what = "globals with readers in many files" if owner == "shared" else f"globals owned by {owner}"
        open(f"{DATA_DIR}/{owner}.md", "w").write(HEADER.format(title=f"{owner}: {len(addrs)} {what}") + "\n".join(lines) + "\n")
    index = [HEADER.format(title="Data map index"),
             f"All {len(G)} globals are in `globals.tsv`, one row per address, in {len(D['groups'])} address groups. "
             "Each global is listed on the page of its owner file, the file of most of the functions that touch it. "
             "A global that four or more files touch, with no file holding half of them, is on `shared.md`.", "",
             f"- Confidence: {conf['high']} high, {conf['medium']} medium, {conf['low']} low.",
             f"- Model: {', '.join(f'{n} {m}' for m, n in model.most_common())}.",
             f"- Runs: {', '.join(runs)}.",
             "- Script names: key ids from the name chains of the key id load (0x601a40), read-only float constants by value, "
             "vtables by the constructor or destructor that stores them, string pointers, and globals that only library code touches.", "",
             "| Owner file | Globals |", "|---|---|"]
    for owner in sorted(by_owner, key=lambda o: (o == "shared", o.lower())):
        index.append(f"| [{owner}]({owner}.md) | {len(by_owner[owner])} |")
    open(f"{DATA_DIR}/index.md", "w").write("\n".join(index) + "\n")
    print(len(by_owner), "pages", dict(conf), dict(model))


if __name__ == "__main__":
    main(sys.argv[1:])
